"""Every spawn has a stated fallback, and Gate 1 never codes inline.

Story 2 of 2026-11-08-writ-agents-registered. A session that started before
the `writ-*` agents were registered lists no `writ-*` type. The adapter names
the general-purpose fallback, Gate 1 routes to it or to BLOCKED escalation,
and the supervisor ESCALATEs code that no coding-agent spawn produced. Each
sentence must also reach the generated copies the generators write.
"""

from pathlib import Path

REPO = Path(__file__).resolve().parents[2]

ADAPTER = REPO / "adapters" / "claude-code.md"
IMPLEMENT_STORY = REPO / "commands" / "implement-story.md"
SUPERVISOR = REPO / "agents" / "supervisor-agent.md"

# Generated by scripts/gen-platform-trees.py from commands/implement-story.md.
IMPLEMENT_STORY_COPIES = (
    REPO / "cursor" / "plugin" / "commands" / "implement-story.md",
    REPO / "plugins" / "writ" / "commands" / "implement-story.md",
)
# Generated by scripts/gen-claude-agents.py from agents/supervisor-agent.md.
SUPERVISOR_COPY = REPO / "claude-code" / "agents" / "writ-supervisor.md"

ADAPTER_SENTENCE = (
    "When the session lists no `writ-*` type (it started before the agents were "
    "installed, or the harness has none), spawn a general-purpose agent whose "
    "prompt begins \"Read and follow `agents/<file>.md`\", with the same inputs. "
    "Name the agent type that ran in the report."
)
GATE1_SENTENCE = (
    "No coding-agent type: spawn per the adapter's Agent Paths fallback; if "
    "nothing can be spawned, BLOCKED escalation. The orchestrator never codes "
    "a story itself."
)
SUPERVISOR_CLAUSE = "code in the commit range with no coding-agent spawn in the report"


def read(path):
    return path.read_text(encoding="utf-8")


def section(text, start, end):
    begin = text.index(start)
    return text[begin:text.index(end, begin + len(start))]


def escalate_line(text):
    lines = [line for line in text.splitlines() if line.startswith("- ESCALATE:")]
    assert len(lines) == 1, lines
    return lines[0]


def test_adapter_states_the_general_purpose_fallback():
    """AC-2.1: § Agent Paths follows the spawn-by-name rule with the fallback."""
    paths = section(read(ADAPTER), "### Agent Paths", "### Triggering Agents")
    by_name = "Spawn the `writ-*` agent by name."
    assert by_name in paths
    assert ADAPTER_SENTENCE in paths
    assert paths.index(by_name) < paths.index(ADAPTER_SENTENCE)


def test_gate1_routes_a_missing_coding_type_never_inline():
    """AC-2.2: Gate 1 states the fallback, BLOCKED, and no inline coding."""
    for path in (IMPLEMENT_STORY,) + IMPLEMENT_STORY_COPIES:
        gate1 = section(read(path), "#### Gate 1: Coding Agent", "#### Gate 2:")
        assert GATE1_SENTENCE in gate1, path.relative_to(REPO)


def test_supervisor_escalates_code_with_no_coding_spawn():
    """AC-2.3: the ESCALATE rule names code with no coding-agent spawn."""
    for path in (SUPERVISOR, SUPERVISOR_COPY):
        assert SUPERVISOR_CLAUSE in escalate_line(read(path)), path.relative_to(REPO)
